/**
 * The bridge from connectors people set up in chat (the workspace's MCP *sources*) to MemWise
 * plugins (docs/memwise/22-phase-4-interfaces.md §7, the Connectors plugin).
 *
 * - `resolveMcpSource(slug)` is the kernel's `KernelOptions.resolveMcpSource`: a plugin server
 *   declared `{ source: <slug> }` is resolved when it is connected, from the source's config and
 *   the app's credential store (the same `SourceServerBuilder` path chat sessions use), so nothing
 *   secret is ever written into the project folder.
 * - `sourcePluginFolders()` writes, for each enabled MCP source, a plugin folder
 *   `source/<slug>` (`trust: local`, one server `{ source: <slug> }`, no tools: the kernel lists
 *   them at install) that `kernel.plugins.install(dir)` can install.
 *
 * Which workspace: the MemWise service is not tied to a workspace, so the bridge reads the one
 * named by `workspaceRoot` (service option), else `MEMWISE_WORKSPACE_DIR`, else the app's active
 * workspace in `<configDir>/config.json`, looked up again on every call. No workspace, or no
 * sources, simply means nothing to resolve or list.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { homedir } from 'node:os'
import { join } from 'node:path'
import type { McpServerDef } from '@memwise/defs'

export interface ConnectorLogger { warn(...args: unknown[]): void }

export interface ConnectorBridgeOptions {
  /** `~/.memwise`: holds `config.json` (the workspaces) and the generated plugin folders. */
  configDir: string
  /** The workspace whose sources are bridged; default `MEMWISE_WORKSPACE_DIR`, else the active one. */
  workspaceRoot?: string | (() => string | undefined)
  /** Where the generated `source/<slug>` plugin folders go; default `<configDir>/memwise/source-plugins`. */
  cacheDir?: string
  logger?: ConnectorLogger
}

/** A source that can be installed as a plugin. */
export interface SourcePluginFolder {
  /** The source's slug; the plugin is `source/<slug>`. */
  slug: string
  /** The source's name, the plugin's title. */
  name: string
  /** The generated plugin folder, for `kernel.plugins.install(dir)`. */
  dir: string
}

export interface ConnectorBridge {
  resolveMcpSource(slug: string): Promise<McpServerDef | undefined>
  /** Writes (and refreshes) a plugin folder for every enabled MCP source; removes the folders of sources that are gone. */
  sourcePluginFolders(): Promise<SourcePluginFolder[]>
  /** The workspace the bridge reads now, if any. */
  workspaceRoot(): string | undefined
}

/** A source slug is a folder name: no separators, no dots at the start. */
const SAFE_SLUG = /^[A-Za-z0-9][A-Za-z0-9_-]*$/

/** `source/<slug>`: plugin ids are lower case (PLUGIN_ID_PATTERN). */
export function sourcePluginId(slug: string): string {
  return `source/${slug.toLowerCase().replace(/[^a-z0-9._-]+/g, '-')}`
}

function expandHome(p: string): string {
  const home = homedir()
  return p.replace(/^~(?=$|[\\/])/, home).replace(/\$\{HOME\}/g, home)
}

/**
 * The app's active workspace as `<configDir>/config.json` records it (the first one when none is
 * marked active). Read without side effects: nothing is created or migrated.
 */
export function activeWorkspaceRoot(configDir: string): string | undefined {
  try {
    const config = JSON.parse(readFileSync(join(configDir, 'config.json'), 'utf8')) as {
      workspaces?: { id?: string; rootPath?: string }[]
      activeWorkspaceId?: string | null
    }
    const workspaces = Array.isArray(config.workspaces) ? config.workspaces.filter((w) => typeof w?.rootPath === 'string') : []
    const ws = workspaces.find((w) => w.id === config.activeWorkspaceId) ?? workspaces[0]
    return ws?.rootPath ? expandHome(ws.rootPath) : undefined
  } catch {
    return undefined
  }
}

/** YAML double-quoted scalar (JSON strings are valid YAML). */
const q = (s: string) => JSON.stringify(s)

/** The generated manifest of a source's plugin. Deterministic, so installing it again is a no-op. */
export function sourcePluginManifest(slug: string, name: string): string {
  return [
    '# Generated by MemWise from a connector set up in the app (the Connectors plugin, docs/memwise/22 §7).',
    '# The server is resolved when it is used, with the source\'s stored credentials: nothing secret is here.',
    `id: ${sourcePluginId(slug)}`,
    'version: 1.0.0',
    `title: ${q(name)}`,
    `description: ${q(`The connector "${name}" set up in the app, as a plugin. Its tools are found when it is installed.`)}`,
    'trust: local',
    'mcp_servers:',
    `  ${q(slug)}: { source: ${q(slug)} }`,
    '',
  ].join('\n')
}

type SharedSources = typeof import('@memwise/shared/sources')

export function createConnectorBridge(opts: ConnectorBridgeOptions): ConnectorBridge {
  const cacheDir = opts.cacheDir ?? join(opts.configDir, 'memwise', 'source-plugins')
  const warn = (...args: unknown[]) => opts.logger?.warn(...args)

  const workspaceRoot = (): string | undefined => {
    const given = typeof opts.workspaceRoot === 'function' ? opts.workspaceRoot() : opts.workspaceRoot
    const root = given ?? process.env.MEMWISE_WORKSPACE_DIR ?? activeWorkspaceRoot(opts.configDir)
    return root && existsSync(root) ? root : undefined
  }

  // The sources module pulls in the agent SDK: load it only when a source is actually used.
  let shared: Promise<SharedSources> | undefined
  const sources = () => (shared ??= import('@memwise/shared/sources'))

  const loadMcpSource = async (root: string, slug: string) => {
    if (!SAFE_SLUG.test(slug)) return undefined
    const { loadSource } = await sources()
    const source = loadSource(root, slug)
    if (!source || source.config.type !== 'mcp' || !source.config.mcp || !source.config.enabled) return undefined
    return source
  }

  return {
    workspaceRoot,

    async resolveMcpSource(slug) {
      const root = workspaceRoot()
      if (!root) return undefined
      try {
        const source = await loadMcpSource(root, slug)
        if (!source) return undefined
        const { getSourceCredentialManager, getSourceServerBuilder, isSourceUsable } = await sources()
        if (!isSourceUsable(source)) {
          warn(`[memwise] the connector ${slug} needs to be signed in again before playbooks can use it`)
          return undefined
        }
        const mcp = source.config.mcp!
        const creds = getSourceCredentialManager()
        let token: string | null = null
        let credential: Awaited<ReturnType<typeof creds.getApiCredential>> = null
        if (mcp.transport !== 'stdio') {
          if (mcp.authType && mcp.authType !== 'none') {
            token = await creds.getToken(source)
            // An OAuth token near or past its expiry is refreshed here, as a chat session would.
            const stored = await creds.load(source)
            if (stored?.refreshToken && (!token || creds.needsRefresh(stored))) {
              try { token = (await creds.refresh(source)) ?? token } catch (e) {
                warn(`[memwise] refreshing the sign-in of ${slug} failed: ${e instanceof Error ? e.message : String(e)}`)
              }
            }
          }
          if (mcp.headerNames?.length) credential = await creds.getApiCredential(source)
        }
        const built = getSourceServerBuilder().buildMcpServer(source, token, credential)
        if (!built) return undefined
        if (built.type === 'stdio') {
          return {
            command: built.command,
            ...(built.args?.length ? { args: [...built.args] } : {}),
            ...(built.env && Object.keys(built.env).length ? { env: { ...built.env } } : {}),
          }
        }
        // `sse` sources are given as a URL too; the kernel's client picks the transport.
        return { url: built.url, ...(built.headers && Object.keys(built.headers).length ? { headers: { ...built.headers } } : {}) }
      } catch (e) {
        warn(`[memwise] could not resolve the connector ${slug}: ${e instanceof Error ? e.message : String(e)}`)
        return undefined
      }
    },

    async sourcePluginFolders() {
      const root = workspaceRoot()
      const out: SourcePluginFolder[] = []
      if (root) {
        let entries: string[] = []
        try {
          entries = readdirSync(join(root, 'sources'), { withFileTypes: true }).filter((e) => e.isDirectory()).map((e) => e.name).sort()
        } catch { /* no sources folder: nothing to list */ }
        for (const slug of entries) {
          try {
            const source = await loadMcpSource(root, slug)
            if (!source) continue
            const name = source.config.name || slug
            const dir = join(cacheDir, slug)
            mkdirSync(dir, { recursive: true })
            const file = join(dir, 'memwise-plugin.yaml')
            const text = sourcePluginManifest(slug, name)
            let current: string | undefined
            try { current = readFileSync(file, 'utf8') } catch { /* new */ }
            if (current !== text) writeFileSync(file, text)
            out.push({ slug, name, dir })
          } catch (e) {
            warn(`[memwise] skipped the connector ${slug}: ${e instanceof Error ? e.message : String(e)}`)
          }
        }
      }
      // Folders of sources that were removed or disabled (or of another workspace) go.
      const keep = new Set(out.map((s) => s.slug))
      try {
        for (const e of readdirSync(cacheDir, { withFileTypes: true })) {
          if (e.isDirectory() && !keep.has(e.name)) rmSync(join(cacheDir, e.name), { recursive: true, force: true })
        }
      } catch { /* no cache yet */ }
      return out
    },
  }
}
